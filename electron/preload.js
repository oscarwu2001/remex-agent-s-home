  saveLayout: (layout) => ipcRenderer.invoke('home:save-layout', layout),
  saveDecor: (decor) => ipcRenderer.invoke('home:save-decor', decor),
  weatherSearch: (name) => ipcRenderer.invoke('home:weather-search', name),
  weatherNow: (place, unit) => ipcRenderer.invoke('home:weather-now', place, unit),
  fieldSet: (change) => ipcRenderer.invoke('home:field-set', change),
  fieldChooseKey: () => ipcRenderer.invoke('home:field-choose-key'),
  fieldRefresh: () => ipcRenderer.invoke('home:field-refresh'),
  fieldCopyReader: () => ipcRenderer.invoke('home:field-copy-reader'),
  fieldSaveSecret: (secret) => ipcRenderer.invoke('home:field-save-secret', secret),
  fieldCopyScript: () => ipcRenderer.invoke('home:field-copy-script'),
  lineSet: (change) => ipcRenderer.invoke('home:line-set', change),
  lineChooseFolder: () => ipcRenderer.invoke('home:line-choose-folder'),
  lineAdd: (req) => ipcRenderer.invoke('home:line-add', req),
  lineTargets: () => ipcRenderer.invoke('home:line-targets'),
  lineBrowse: () => ipcRenderer.invoke('home:line-browse'),
  lineStart: (req) => ipcRenderer.invoke('home:line-start', req),
  lineBotSet: (change) => ipcRenderer.invoke('home:line-bot-set', change),
  lineBotSaveSecret: (secret) => ipcRenderer.invoke('home:line-bot-save-secret', secret),
