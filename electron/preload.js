  packInstall: (names) => ipcRenderer.invoke('pack:install', names),
  packUpdate: () => ipcRenderer.invoke('pack:update'),
  logTail: (which) => ipcRenderer.invoke('home:log-tail', which),
  logOpen: () => ipcRenderer.invoke('home:log-open'),
