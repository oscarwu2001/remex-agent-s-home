  buildReport: (days, details) => ipcRenderer.invoke('home:build-report', days, details),
  showReportFiles: () => ipcRenderer.invoke('home:show-report-files'),
  fleetChoose: () => ipcRenderer.invoke('home:fleet-choose'),
